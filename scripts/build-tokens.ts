/**
 * Emits src/styles/tokens.css from src/styles/tokens.json, the only place design values live.
 * Never edit tokens.css by hand.
 *
 * The page follows the system theme; `data-theme` on <html> (set by the theme toggle) overrides it.
 *
 * Usage: node scripts/build-tokens.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const TOKENS_PATH = fileURLToPath(new URL('../src/styles/tokens.json', import.meta.url));
const CSS_PATH = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
const INDENT = '    ';

type Flat = Record<string, string | number>;

interface TypeRole {
    size: string;
    weight: number;
    leading: number;
    tracking: string;
    family: string;
}

/** `lineDotcms` → `line-dotcms`. Pure. */
export function kebab(name: string): string {
    return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/** One `--prefix-key: value;` line per entry. Pure. */
export function declarations(prefix: string, values: Flat): string[] {
    return Object.entries(values).map(([key, value]) => `--${prefix}-${kebab(key)}: ${value};`);
}

function typeDeclarations(roles: Record<string, TypeRole>): string[] {
    return Object.entries(roles).flatMap(([role, spec]) => [
        `--type-${role}-size: ${spec.size};`,
        `--type-${role}-weight: ${spec.weight};`,
        `--type-${role}-leading: ${spec.leading};`,
        `--type-${role}-tracking: ${spec.tracking};`,
        `--type-${role}-family: var(--font-${spec.family});`
    ]);
}

function block(selector: string, lines: string[], depth = 0): string {
    const pad = INDENT.repeat(depth);
    const body = lines.map((line) => `${pad}${INDENT}${line}`).join('\n');

    return `${pad}${selector} {\n${body}\n${pad}}`;
}

function main(): void {
    const tokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
    const dark = declarations('color', tokens.color.dark);
    const light = declarations('color', tokens.color.light);

    const shared = [
        ...declarations('font', tokens.font),
        ...typeDeclarations(tokens.type),
        ...declarations('space', tokens.space),
        ...declarations('radius', tokens.radius),
        ...declarations('route', tokens.route),
        ...declarations('motion', tokens.motion),
        ...declarations('layout', tokens.layout)
    ];

    const css = [
        '/* Generated by scripts/build-tokens.ts from tokens.json. Do not edit. */',
        block(':root', ['color-scheme: light dark;', ...shared, ...light]),
        block(':root[data-theme="light"]', ['color-scheme: light;']),
        '@media (prefers-color-scheme: dark) {',
        block(':root:not([data-theme="light"])', ['color-scheme: dark;', ...dark], 1),
        '}',
        block(':root[data-theme="dark"]', ['color-scheme: dark;', ...dark]),
        ''
    ].join('\n');

    writeFileSync(CSS_PATH, css);
    console.log(`Wrote ${CSS_PATH}`);
}

main();
